-- SIGRE · SOLO LECTURA · Extrae la estructura del esquema public (DDL ordenado) y los catálogos semilla.
-- No lee usuarios, emprendedores, auditorías ni ningún dato personal: la única data exportada son los catálogos
-- roles, app_modulos, app_acciones, app_pantallas, pantalla_acciones, rol_pantalla_permisos y municipios.
-- Uso: SQL Editor de STAGING → Run → Export → Download CSV. Columnas: fase, orden, objeto, ddl.
-- El CSV se transforma con supabase/scripts/esquema_base_generar.py en las migraciones 20261001000000 (estructura) y 20261001000100 (catálogos).

WITH
tablas AS (
    SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
),
funciones AS (
    SELECT p.oid, p.proname, p.proacl, pg_get_function_identity_arguments(p.oid) AS args
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
roles_api AS (SELECT unnest(ARRAY['anon', 'authenticated', 'service_role']) AS rolname),
ddl AS (
    -- 20 · Tablas (columnas, tipos, identidad, valores por defecto, NOT NULL)
    SELECT 20 AS fase, t.relname AS orden, 'table:' || t.relname AS objeto,
           format(E'CREATE TABLE public.%I (\n%s\n);', t.relname, string_agg(
               format('    %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                      CASE a.attidentity WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                                         WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' ELSE '' END,
                      CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                           WHEN ad.adbin IS NOT NULL AND a.attidentity = '' THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                           ELSE '' END,
                      CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
               E',\n' ORDER BY a.attnum)) AS ddl
    FROM tablas t
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    GROUP BY t.relname

    -- 30 · Restricciones PK / UNIQUE / CHECK / EXCLUDE · 35 · claves foráneas
    UNION ALL
    SELECT CASE WHEN co.contype = 'f' THEN 35 ELSE 30 END,
           t.relname || '.' || CASE co.contype WHEN 'p' THEN '0' WHEN 'u' THEN '1' ELSE '2' END || co.conname,
           'constraint:' || t.relname || '.' || co.conname,
           format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
    FROM pg_constraint co JOIN tablas t ON t.oid = co.conrelid
    WHERE co.contype IN ('p', 'u', 'c', 'x', 'f') AND co.conislocal

    -- 40 · Índices que no respaldan una restricción
    UNION ALL
    SELECT 40, t.relname || '.' || ic.relname, 'index:' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
    FROM pg_index i JOIN tablas t ON t.oid = i.indrelid JOIN pg_class ic ON ic.oid = i.indexrelid
    WHERE NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = i.indexrelid AND co.conrelid = i.indrelid)

    -- 50 · Funciones
    UNION ALL
    SELECT 50, f.proname || '(' || f.args || ')', 'function:' || f.proname || '(' || f.args || ')',
           rtrim(pg_get_functiondef(f.oid), E'\n') || ';'
    FROM funciones f

    -- 60 · RLS por tabla
    UNION ALL
    SELECT 60, t.relname, 'rls:' || t.relname,
           format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
           || CASE WHEN t.relforcerowsecurity THEN format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname) ELSE '' END
    FROM tablas t WHERE t.relrowsecurity

    -- 70 · Políticas
    UNION ALL
    SELECT 70, t.relname || '.' || po.polname, 'policy:' || t.relname || '.' || po.polname,
           format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', po.polname, t.relname,
                  CASE WHEN po.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
                  CASE po.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE'
                                 WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
                  CASE WHEN po.polroles = '{0}' THEN 'PUBLIC'
                       ELSE (SELECT string_agg(quote_ident(r.rolname), ', ' ORDER BY r.rolname)
                             FROM pg_roles r WHERE r.oid = ANY (po.polroles)) END,
                  CASE WHEN po.polqual IS NOT NULL THEN E'\n  USING (' || pg_get_expr(po.polqual, po.polrelid) || ')' ELSE '' END,
                  CASE WHEN po.polwithcheck IS NOT NULL THEN E'\n  WITH CHECK (' || pg_get_expr(po.polwithcheck, po.polrelid) || ')' ELSE '' END)
    FROM pg_policy po JOIN tablas t ON t.oid = po.polrelid

    -- 80 · Triggers
    UNION ALL
    SELECT 80, t.relname || '.' || tg.tgname, 'trigger:' || t.relname || '.' || tg.tgname,
           pg_get_triggerdef(tg.oid, false) || ';'
    FROM pg_trigger tg JOIN tablas t ON t.oid = tg.tgrelid
    WHERE NOT tg.tgisinternal

    -- 90 · Permisos de tablas para los roles de la API (se revoca el default de Supabase y se concede lo real)
    UNION ALL
    SELECT 90, t.relname, 'grant:table:' || t.relname,
           format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated, service_role;', t.relname)
           || coalesce(E'\n' || (SELECT string_agg(format('GRANT %s ON TABLE public.%I TO %I;', g.privs, t.relname, g.rolname), E'\n' ORDER BY g.rolname)
                                 FROM (SELECT r.rolname, string_agg(x.privilege_type, ', ' ORDER BY x.privilege_type) AS privs
                                       FROM aclexplode(t.relacl) x JOIN pg_roles r ON r.oid = x.grantee
                                       WHERE r.rolname IN (SELECT rolname FROM roles_api)
                                       GROUP BY r.rolname) g), '')
    FROM tablas t

    -- 91 · Permisos por columna
    UNION ALL
    SELECT 91, t.relname || '.' || a.attname || '.' || r.rolname, 'grant:column:' || t.relname || '.' || a.attname || '.' || r.rolname,
           format('GRANT %s (%I) ON TABLE public.%I TO %I;', string_agg(x.privilege_type, ', ' ORDER BY x.privilege_type), a.attname, t.relname, r.rolname)
    FROM tablas t
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attacl IS NOT NULL
    CROSS JOIN LATERAL aclexplode(a.attacl) x
    JOIN pg_roles r ON r.oid = x.grantee
    WHERE r.rolname IN (SELECT rolname FROM roles_api)
    GROUP BY t.relname, a.attname, r.rolname

    -- 92 · Permisos de ejecución de funciones (proacl NULL = valor por defecto: PUBLIC)
    UNION ALL
    SELECT 92, f.proname || '(' || f.args || ')', 'grant:function:' || f.proname || '(' || f.args || ')',
           format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated, service_role;', f.proname, f.args)
           || coalesce(E'\n' || (SELECT string_agg(format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', f.proname, f.args,
                                                         CASE WHEN x.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(r.rolname) END),
                                                  E'\n' ORDER BY coalesce(r.rolname, ''))
                                 FROM aclexplode(coalesce(f.proacl, acldefault('f', (SELECT proowner FROM pg_proc WHERE oid = f.oid)))) x
                                 LEFT JOIN pg_roles r ON r.oid = x.grantee
                                 WHERE x.privilege_type = 'EXECUTE' AND (x.grantee = 0 OR r.rolname IN (SELECT rolname FROM roles_api))), '')
    FROM funciones f

    -- 95 · Event trigger (lo crea Supabase con «Enable automatic RLS»; se documenta, no se migra)
    UNION ALL
    SELECT 95, e.evtname, 'event_trigger:' || e.evtname,
           format('CREATE EVENT TRIGGER %I ON %s%s EXECUTE FUNCTION %s();', e.evtname, e.evtevent,
                  CASE WHEN e.evttags IS NOT NULL THEN ' WHEN TAG IN (' || (SELECT string_agg(quote_literal(tag), ', ') FROM unnest(e.evttags) tag) || ')' ELSE '' END,
                  e.evtfoid::regproc)
    FROM pg_event_trigger e
    WHERE e.evtfoid IN (SELECT oid FROM funciones)
),
catalogo AS (
              SELECT 201 AS fase, 'roles' AS tabla, to_jsonb(x) AS r FROM public.roles x
    UNION ALL SELECT 202, 'app_modulos', to_jsonb(x) FROM public.app_modulos x
    UNION ALL SELECT 203, 'app_acciones', to_jsonb(x) FROM public.app_acciones x
    UNION ALL SELECT 204, 'app_pantallas', to_jsonb(x) FROM public.app_pantallas x
    UNION ALL SELECT 205, 'pantalla_acciones', to_jsonb(x) FROM public.pantalla_acciones x
    UNION ALL SELECT 206, 'rol_pantalla_permisos', to_jsonb(x) FROM public.rol_pantalla_permisos x
    UNION ALL SELECT 207, 'municipios', to_jsonb(x) FROM public.municipios x
),
semilla AS (
    SELECT fase, tabla || ':' || coalesce(r ->> 'id', md5(r::text)) AS orden, 'seed:' || tabla AS objeto,
           format('INSERT INTO public.%I SELECT * FROM jsonb_populate_record(NULL::public.%I, %L);', tabla, tabla, r::text) AS ddl
    FROM catalogo
)
SELECT fase, orden, objeto, ddl FROM ddl
UNION ALL
SELECT fase, orden, objeto, ddl FROM semilla
ORDER BY fase, orden;
