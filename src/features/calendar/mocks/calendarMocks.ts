import {addDays, startOfDay, startOfWeek} from '../utils/dateUtils'
import type { OrientacionSession, PitchSession } from "../types/calendar";

function at(base: Date, dayOffset: number, time: string): Date {
  const [hours = 0, minutes = 0] = time.split(":").map(Number);
  const day = addDays(base, dayOffset);
  return new Date(day.getFullYear(), day.getMonth(), day.getDate(), hours, minutes);
}

